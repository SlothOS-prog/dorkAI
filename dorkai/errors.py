"""
errors.py — собственные исключения проекта dorkAI.

Зачем нужны свои исключения:
  * код наверху (CLI) ловит ОДИН базовый тип DorkAIError
    и печатает понятное человеку сообщение вместо сырого трейсбека;
  * по имени исключения сразу ясно, ЧТО именно сломалось.
"""


class DorkAIError(Exception):
    """Базовый класс всех ошибок dorkAI.

    Любая наша ошибка наследуется отсюда — это позволяет
    в CLI сделать `except DorkAIError` и перехватить всё разом.
    """


class MissingAPIKeyError(DorkAIError):
    """Вызывается, когда API-ключ не задан ни в .env, ни в переменных окружения.

    Мы не храним ключи в коде (небезопасно), поэтому требуем,
    чтобы пользователь заполнил переменную DORKAI_API_KEY в файле .env.
    """


class EmptyTopicError(DorkAIError):
    """Пользователь передал пустую (или состоящую из пробелов) тему запроса."""


class ModelOutputError(DorkAIError):
    """Модель вернула ответ, который не удалось разобрать как JSON с дорками."""
