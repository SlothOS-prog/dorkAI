"""
exceptions.py — централизованные исключения проекта dorkAI.

Идея: все ошибки домена наследуются от одного базового класса,
чтобы вызывающий код мог поймать «любую ошибку dorkAI» одним except.
"""

# Базовое исключение всего приложения — от него наследуются все остальные
class DorkAIError(Exception):
    """Корневая ошибка dorkAI: позволяет ловить любые наши исключения разом."""


# Ошибка «у пользователя нет API-ключа» — интерфейс должен предложить его ввести
class MissingApiKeyError(DorkAIError):
    """API-ключ не задан ни в переменных окружения, ни в файле .env."""


# Ошибка сетевого/протокольного уровня при общении с ИИ-провайдером
class AiClientError(DorkAIError):
    """Проблемы HTTP-слоя: таймаут, сеть, 4xx/5xx, неверный ключ, пустой ответ."""


# Ошибка разбора ответа ИИ (например, модель вернула не JSON)
class ResponseParsingError(DorkAIError):
    """Ответ модели не удалось привести к ожидаемой JSON-структуре с дорками."""


# Ошибка валидации ввода пользователя (пустой запрос и т. п.)
class EmptyQueryError(DorkAIError):
    """Пользователь отправил пустую строку запроса."""
